"""Figure: the certified band on a four-piece surrogate.

The threshold tau_j is read off the LOWER envelope P^- and membership tested
against the UPPER envelope P^+.  The asymmetry is forced: B_j is the set of
scenarios that cannot be excluded, not those predicted to lie in the tail.
Scenarios outside the band cannot enter the top m and are never revalued.

Emits a standalone PGF/TikZ file so the figure in the paper is generated by the
same code as the numbers.
"""
import argparse, sys
import numpy as np
sys.path.insert(0, "..")
from certproj import Projection, certified_band, assert_version
from certproj.data import synthetic_catalogue
from certproj.populations import bond_books


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("-N", type=int, default=260)
    ap.add_argument("--alpha", type=float, default=0.90)
    ap.add_argument("-K", type=int, default=4)
    ap.add_argument("--seed", type=int, default=3)
    ap.add_argument("--out", default="../results/figure_band.tex")
    a = ap.parse_args()
    assert_version()

    F = synthetic_catalogue(a.N, seed=a.seed)
    c = bond_books(1, m=4, K=a.K, seed=a.seed)[0]
    proj = Projection(F, 1)
    m = int(np.ceil((1 - a.alpha) * a.N))

    z = proj.z.ravel()
    o = np.argsort(z)
    z, surr = z[o], proj.surrogate(c)[o]
    delta = proj.gamma(c) * proj.enorm[o]
    lo, hi = surr - delta, surr + delta
    band = certified_band(surr, delta, m)
    tau = float(np.partition(lo, a.N - m)[a.N - m])

    true = c.evaluate(F)[o]
    top = np.argpartition(true, a.N - m)[a.N - m:]
    assert band[top].all(), "band does not contain the true tail set"

    print(f"N={a.N}, alpha={a.alpha}, K={a.K}, m={m}")
    print(f"tau_j = {tau:.4f}")
    print(f"band  = {band.sum()} of {a.N} scenarios ({band.mean():.1%})")
    print(f"provably excluded = {(~band).sum()} ({1 - band.mean():.1%})")
    print("band contains the true tail set: True")

    def coords(x, y):
        return " ".join(f"({xi:.6f},{yi:.6f})" for xi, yi in zip(x, y))

    with open(a.out, "w") as fh:
        fh.write(
            "% Generated by exp15_figure_band.py -- do not edit by hand.\n"
            "\\begin{tikzpicture}\n"
            "\\begin{axis}[width=\\linewidth,height=6cm,"
            "xlabel={retained coordinate $z$ (scenarios in sorted order)},"
            "ylabel={loss},legend pos=north west,legend cell align=left,"
            "tick label style={font=\\small},label style={font=\\small},"
            "legend style={font=\\scriptsize}]\n"
            f"\\addplot[name path=up,draw=none] coordinates {{{coords(z, hi)}}};\n"
            f"\\addplot[name path=dn,draw=none] coordinates {{{coords(z, lo)}}};\n"
            "\\addplot[gray!25] fill between[of=up and dn];\n"
            f"\\addlegendentry{{$[P^-_{{ji}},P^+_{{ji}}]$}}\n"
            f"\\addplot[thick,black] coordinates {{{coords(z, surr)}}};\n"
            "\\addlegendentry{surrogate $\\widetilde P_{ji}$}\n"
            f"\\addplot[dashed,black] coordinates "
            f"{{({z.min():.6f},{tau:.6f}) ({z.max():.6f},{tau:.6f})}};\n"
            "\\addlegendentry{$\\tau_j$}\n"
            "\\end{axis}\n\\end{tikzpicture}\n")
    print(f"\nwrote {a.out}")
